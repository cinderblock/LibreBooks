// Empty records with every field present, for new forms and quick-create. The
// server fills ids when they're omitted, but the API also accepts a client id,
// which lets a form keep a stable key for its lines before the first save.

import type {
  Account,
  AccountType,
  Address,
  Entity,
  EntityKind,
  Item,
  ItemType,
  Txn,
  TxnLine,
  TxnType,
} from './types';

export function newId(): string {
  return crypto.randomUUID();
}

export function blankAddress(): Address {
  return { lines: [], city: null, state: null, postal_code: null, country: null, note: null };
}

export function blankAccount(name: string, account_type: AccountType, parent?: Account | null): Account {
  return {
    id: newId(),
    name,
    full_name: parent ? `${parent.full_name}:${name}` : name,
    parent_id: parent?.id ?? null,
    sublevel: parent ? parent.sublevel + 1 : 0,
    account_type,
    number: null,
    description: null,
    bank_account_number: null,
    tax_line: null,
    role: null,
    is_active: true,
    currency: null,
    cash_flow_class: null,
    edit_seq: 0,
  };
}

